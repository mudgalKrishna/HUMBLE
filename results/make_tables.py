"""Regenerate results/TABLES.md from results/runs/*. No model needed."""
import glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
HDR = ("| Run | n | Accuracy | Confident wrong (95% CI) | SelAcc@80 | Unnecessary abstention "
       "| Unanswerable bluff | ECE | Format failure |\n|---|---|---|---|---|---|---|---|---|")


def row(run, m):
    ci = m.get("cw_ci95")
    cis = f"[{ci[0]:.3f}, {ci[1]:.3f}]" if ci else "-"
    return (f"| {run} | {m['n']} | {m['accuracy']:.3f} | {m['cw']:.3f} {cis} | {m['sel_acc_80']:.3f} "
            f"| {m['unnecessary_abstention']:.3f} | {m['unanswerable_bluff']:.3f} | {m['ece']:.3f} "
            f"| {m['format_failure']:.3f} |")


def section(split):
    rows = []
    for f in sorted(glob.glob(os.path.join(HERE, "runs", "*", split, "metrics.json"))):
        run = os.path.normpath(f).split(os.sep)[-3]
        rows.append(row(run, json.load(open(f, encoding="utf-8"))))
    return HDR + "\n" + "\n".join(rows) if rows else "_no runs yet_"


out = ["# Result tables (generated by make_tables.py)", "",
       "## Synthetic test split (locked, evaluated once)", "", section("test"), "",
       "## Synthetic validation split", "", section("val"), "",
       "## External real-data check (SQuAD 2.0 validation sample, evaluated once)", "", section("external"), "",
       "## Real-text training: validation split (used to choose the unanswerable share)", "", section("real_val"), "",
       "## Real-text training: locked real test (evaluated once)", "", section("real_test"), "",
       "## Iteration 2: fresh validation split (val2)", "", section("val2"), "",
       "## Iteration 2: fresh locked test (test2, evaluated once)", "", section("test2"), ""]
open(os.path.join(HERE, "TABLES.md"), "w", encoding="utf-8").write("\n".join(out))
print("wrote TABLES.md")
