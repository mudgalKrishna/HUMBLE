"""SQuAD 2.0 probe sets (evaluation mode). Licence: CC BY-SA 4.0; derived probes keep it.

Splits are by ARTICLE (document): train pool / probe pool / val / test never share an article.
Paragraphs used anywhere in earlier HUMBLE iterations are excluded from val, test and probe pool,
so the new locked test is fresh.
"""
from __future__ import annotations

import hashlib
import json
import os
import random
from pathlib import Path

from .corpus import Corpus, Paragraph, build_category, pid, wrong_answer_pool, twin_of

CELLS = [("A", "C1", "answerable"), ("U1", "C2", "U1_C2"), ("U1", "C3", "U1_C3"), ("U2", "C1", "U2"),
         ("U3", "C1", "U3"), ("U4", "C1", "U4"), ("U5", "C4", "U5")]
LICENCE = "CC BY-SA 4.0 (derived from SQuAD 2.0, Rajpurkar et al. 2018)"


def load_squad_frames():
    import pandas as pd
    from huggingface_hub import hf_hub_download
    frames = []
    for f in ("train-00000-of-00001.parquet", "validation-00000-of-00001.parquet"):
        p = hf_hub_download("rajpurkar/squad_v2", f"squad_v2/{f}", repo_type="dataset", token=os.environ.get("HF_TOKEN"))
        df = pd.read_parquet(p)
        df["origin"] = "train" if f.startswith("train") else "validation"
        frames.append(df)
    df = pd.concat(frames, ignore_index=True)
    df["unans"] = df["answers"].apply(lambda a: len(a["text"]) == 0)
    return df


def used_paragraph_texts(dirs) -> set:
    """Paragraph texts used by earlier iterations (documents/*.md in each folder)."""
    used = set()
    for d in dirs:
        d = Path(d)
        for f in (d / "documents").glob("*.md") if (d / "documents").exists() else []:
            used.add(f.read_text(encoding="utf-8"))
    return used


def assign_articles(titles, seed, shares=(("test", 0.10), ("val", 0.10), ("probe", 0.20), ("train", 0.60))):
    titles = sorted(titles)
    random.Random(seed).shuffle(titles)
    out, start = {}, 0
    for i, (name, share) in enumerate(shares):
        end = len(titles) if i == len(shares) - 1 else start + round(share * len(titles))
        for t in titles[start:end]:
            out[t] = name
        start = end
    return out


def build(out_dir, cfg, used_texts=frozenset(), descriptors=None, df=None, probe_set="squad3", verify_fn=None,
          overgenerate=1.8):
    """Write the probe set. `descriptors` maps article title -> generic kind (for U4).

    With `verify_fn(items) -> list[bool]` (the sufficient-context judge), each val/test/probe cell is
    over-generated by `overgenerate`, judged, and the first n passing items are kept (plan §6.4).
    """
    pc = cfg["probes"]["squad"]
    k = cfg["prompt"]["passages_default"]
    seed = pc["seed"]
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    df = load_squad_frames() if df is None else df
    split_of = assign_articles(set(df["title"]), seed)
    df = df.assign(split=df["title"].map(split_of))
    fresh = ~df["context"].isin(set(used_texts))
    manifest = {"probe_set": probe_set, "licence": LICENCE, "seed": seed, "passages_per_prompt": k,
                "articles": {s: sorted({t for t, v in split_of.items() if v == s}) for s in ("train", "probe", "val", "test")},
                "excluded_used_paragraphs": int((~fresh).sum()), "cells": {}, "failures": {}}
    all_titles = sorted(set(df["title"]))
    for split in ("val", "test", "probe", "train"):
        sdf = df[(df["split"] == split) & (fresh | (split == "train"))]
        paras = {}
        for ctx, title in zip(sdf["context"], sdf["title"]):
            paras.setdefault(ctx, title)
        corpus = Corpus([Paragraph(pid(t), d, t) for t, d in paras.items()])
        with open(out / f"paragraphs_{split}.jsonl", "w", encoding="utf-8") as f:
            for p in corpus.paragraphs:
                f.write(json.dumps({"id": p.id, "doc": p.doc, "text": p.text}, ensure_ascii=False) + "\n")
        ans_src, un_src = [], []
        first_ans_by_para = {}
        for r in sdf.itertuples():
            s = {"qid": r.id, "question": r.question, "answers": list(dict.fromkeys(r.answers["text"])),
                 "paragraph_id": pid(r.context), "doc": r.title}
            if r.unans:
                un_src.append(s)
            else:
                ans_src.append(s)
                first_ans_by_para.setdefault(s["paragraph_id"], s)
        for s in un_src:
            t = first_ans_by_para.get(s["paragraph_id"])
            if t:
                s["twin_source"] = t
        wrong_pool = wrong_answer_pool(ans_src)
        split_titles = {p.doc for p in corpus.paragraphs}
        outside = [t.replace("_", " ") for t in all_titles if t not in split_titles]
        rng = random.Random(f"{seed}-{split}")
        items = []
        scale = pc["probe_pool_scale"] if split == "probe" else 1
        if split == "train":
            cells = [("A", "C1", pc["train_pool_answerable"]), ("U3", "C1", pc["train_pool_unanswerable"])]
        else:
            cells = [(c, ctx, pc["per_split"][key] * scale) for c, ctx, key in CELLS]
        over = overgenerate if (verify_fn and split != "train") else 1.0
        for cat, ctx, n in cells:
            if cat == "U4" and not descriptors:
                raise RuntimeError("U4 needs article descriptors; run probes.describe first")
            srcs = un_src if cat == "U3" else ans_src
            got, fails = build_category(corpus, rng, probe_set, split, cat, ctx, srcs, int(n * over + 0.999), k,
                                        wrong_pool=wrong_pool, outside_entities=outside, descriptors=descriptors)
            if over > 1.0:
                keep = verify_fn(got)
                passed = [it for it, ok in zip(got, keep) if ok]
                manifest.setdefault("judge", {})[f"{split}/{cat}/{ctx}"] = {
                    "candidates": len(got), "passed": len(passed), "pass_rate": len(passed) / max(1, len(got))}
                got = passed[:n]
            items += got
            manifest["cells"][f"{split}/{cat}/{ctx}"] = {"requested": n, "built": len(got)}
            if fails:
                manifest["failures"][f"{split}/{cat}/{ctx}"] = fails
        trng = random.Random(f"{seed}-{split}-twins")
        for it in items:
            if it["label"] == "abstain":
                tw = twin_of(it, corpus, trng, k)
                it["twin"] = {key: tw[key] for key in ("question", "passages", "gold_passage_index", "gold_answers")} if tw else None
        with open(out / f"items_{split}.jsonl", "w", encoding="utf-8") as f:
            for it in items:
                f.write(json.dumps(it, ensure_ascii=False) + "\n")
    lock = hashlib.sha256((out / "items_test.jsonl").read_bytes()).hexdigest()
    (out / "TEST_LOCK.txt").write_text(lock + "\n", encoding="utf-8")
    manifest["test_lock_sha256"] = lock
    if descriptors:
        (out / "descriptors.json").write_text(json.dumps(descriptors, indent=1, ensure_ascii=False), encoding="utf-8")
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False), encoding="utf-8")
    return manifest


def load_items(probe_dir, split):
    p = Path(probe_dir) / f"items_{split}.jsonl"
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]


def load_corpus(probe_dir, split, language="en"):
    p = Path(probe_dir) / f"paragraphs_{split}.jsonl"
    rows = [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]
    return Corpus([Paragraph(r["id"], r["doc"], r["text"]) for r in rows], language=language)


def used_probe_texts(probe_dirs) -> set:
    """Every passage text shown in any prompt (item or twin) of these probe sets."""
    used = set()
    for d in probe_dirs:
        for f in Path(d).glob("items_*.jsonl"):
            for l in f.read_text(encoding="utf-8").splitlines():
                if l.strip():
                    it = json.loads(l)
                    used.update(it["passages"])
                    if it.get("twin"):
                        used.update(it["twin"]["passages"])
    return used


def build_u45(out_dir, cfg, descriptors, exclude_probe_dirs, df=None, probe_set="squad3u45", n=150,
              verify_fn=None, overgenerate=8.0, from_split="train", used_texts=frozenset()):
    """Fix 2: a larger U4 (underspecified) / U5 (misleading) evaluation set, written as split `test`.

    squad3v's article split covers every SQuAD article, so there are no unassigned articles. Items come
    from `from_split` articles (never squad3v val/test), using only paragraphs that no prompt of the
    `exclude_probe_dirs` probe sets ever showed; distractors come from the same fresh paragraphs.
    Judge pass rates on squad3v were 12-28%, hence the large `overgenerate`.
    """
    pc = cfg["probes"]["squad"]
    k, seed = cfg["prompt"]["passages_default"], pc["seed"]
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    df = load_squad_frames() if df is None else df
    split_of = assign_articles(set(df["title"]), seed)
    assert from_split not in ("val", "test"), "never build from the locked squad3v val/test articles"
    used = used_probe_texts(exclude_probe_dirs) | set(used_texts)
    sdf = df[(df["title"].map(split_of) == from_split) & ~df["context"].isin(used)]
    paras = {}
    for ctx, title in zip(sdf["context"], sdf["title"]):
        paras.setdefault(ctx, title)
    corpus = Corpus([Paragraph(pid(t), d, t) for t, d in paras.items()])
    with open(out / "paragraphs_test.jsonl", "w", encoding="utf-8") as f:
        for p in corpus.paragraphs:
            f.write(json.dumps({"id": p.id, "doc": p.doc, "text": p.text}, ensure_ascii=False) + "\n")
    ans_src = [{"qid": r.id, "question": r.question, "answers": list(dict.fromkeys(r.answers["text"])),
                "paragraph_id": pid(r.context), "doc": r.title} for r in sdf.itertuples() if not r.unans]
    wrong_pool = wrong_answer_pool(ans_src)
    rng = random.Random(f"{seed}-{probe_set}")
    manifest = {"probe_set": probe_set, "licence": LICENCE, "seed": seed, "passages_per_prompt": k,
                "source_split": from_split, "articles": sorted({p.doc for p in corpus.paragraphs}),
                "paragraphs": len(corpus.paragraphs), "excluded_paragraph_texts": len(used),
                "excluded_probe_sets": [str(d) for d in exclude_probe_dirs], "cells": {}, "failures": {}}
    items = []
    over = overgenerate if verify_fn else 1.0
    for cat, ctx in (("U4", "C1"), ("U5", "C4")):
        got, fails = build_category(corpus, rng, probe_set, "test", cat, ctx, ans_src, int(n * over + 0.999), k,
                                    wrong_pool=wrong_pool, descriptors=descriptors)
        if verify_fn:
            keep = verify_fn(got)
            passed = [it for it, ok in zip(got, keep) if ok]
            manifest.setdefault("judge", {})[f"test/{cat}/{ctx}"] = {
                "candidates": len(got), "passed": len(passed), "pass_rate": len(passed) / max(1, len(got))}
            got = passed[:n]
        items += got
        manifest["cells"][f"test/{cat}/{ctx}"] = {"requested": n, "built": len(got)}
        manifest["failures"][f"test/{cat}/{ctx}"] = fails
    with open(out / "items_test.jsonl", "w", encoding="utf-8") as f:
        for it in items:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")
    lock = hashlib.sha256((out / "items_test.jsonl").read_bytes()).hexdigest()
    (out / "TEST_LOCK.txt").write_text(lock + "\n", encoding="utf-8")
    manifest["test_lock_sha256"] = lock
    (out / "descriptors.json").write_text(json.dumps(descriptors, indent=1, ensure_ascii=False), encoding="utf-8")
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False), encoding="utf-8")
    return manifest
