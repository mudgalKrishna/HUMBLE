"""Probe builder for a company's own documents (product mode, plan §6.1 and change #9).

  1 read     .txt / .md / .pdf (pypdf) / .docx (python-docx) from a folder
  2 chunk    ~110-word passages on paragraph boundaries
  3 generate answerable QA per chunk with CuratorKIT's QAGenerationTask, backed by a LOCAL model
  4 ground   CuratorKIT's HallucinationGate (local judge) + an extractive check (answer string in the chunk)
  5 build    the same C1-C4 / U1-U5 probes as the benchmark sets; U3 (false premise) and U4 (underspecified)
             questions are generated by the local model and must be judged insufficient to be kept
  6 split    by document into val / test (and probe pool when there are enough documents); test is locked
No API calls: every model runs on the local GPU.
"""
from __future__ import annotations

import hashlib
import json
import random
import re
import threading
from pathlib import Path

from .corpus import Corpus, Paragraph, build_category, make_item, pid, twin_of, verify_item, wrong_answer_pool, _contains


def read_documents(folder):
    docs = {}
    for p in sorted(Path(folder).rglob("*")):
        if not p.is_file():
            continue
        suf = p.suffix.lower()
        try:
            if suf in (".txt", ".md"):
                docs[p.stem] = p.read_text(encoding="utf-8", errors="ignore")
            elif suf == ".pdf":
                from pypdf import PdfReader
                docs[p.stem] = "\n".join(pg.extract_text() or "" for pg in PdfReader(str(p)).pages)
            elif suf == ".docx":
                import docx
                docs[p.stem] = "\n".join(par.text for par in docx.Document(str(p)).paragraphs)
        except Exception as e:  # unreadable files are reported, not fatal
            docs[f"__error__{p.name}"] = repr(e)
    return docs


def chunk(text, words=110):
    paras = [x.strip() for x in re.split(r"\n\s*\n|\n(?=#)", text) if x.strip()]
    out, cur = [], []
    for para in paras:
        cur.append(para)
        if sum(len(x.split()) for x in cur) >= words:
            out.append(" ".join(cur))
            cur = []
    if cur:
        if out and sum(len(x.split()) for x in cur) < words // 3:
            out[-1] += " " + " ".join(cur)
        else:
            out.append(" ".join(cur))
    return out


class LocalLLM:
    """A CuratorKIT BaseLLM backed by a local transformers model (no API)."""

    def __new__(cls, model, tok, name="local"):
        from curatorkit.llm.base import BaseLLM, LLMResponse
        from ..audit.generate import generate

        class _Local(BaseLLM):
            _lock = threading.Lock()

            def __init__(self):
                super().__init__(model=name, temperature=0.7, max_tokens=512, max_retries=1)

            def _call(self, messages, **kw):
                user = "\n\n".join(m["content"] for m in messages if m["role"] in ("system", "user"))
                temp = kw.get("temperature", 0.7) or 0.0
                with self._lock:
                    out = generate(model, tok, [user], max_new_tokens=int(kw.get("max_tokens", 512)), n=1,
                                   temperature=temp, batch_size=1)[0][0]
                return LLMResponse(text=out, model=name)

        return _Local()


QA_PROMPT = ("Write {num_questions} question-answer pairs about the passage below. Each answer MUST be a short "
             "phrase of at most 8 words copied exactly, word for word, from the passage (a name, number, date, "
             "duration or short phrase). Reply with a JSON array only, like "
             "[{{\"question\": \"...\", \"answer\": \"...\"}}].\n\nPassage:\n{context}")
U3_PROMPT = ("Read the passage and write ONE question that sounds like it is about the passage but assumes a "
             "false fact (a false premise), so the passage cannot answer it. Reply with the question only.\n\nPassage:\n{p}")
U4_PROMPT = ("Read the passages and write ONE short question that is ambiguous: it could refer to more than one "
             "thing mentioned below, each with a different answer, so it cannot be answered without clarification. "
             "Reply with the question only.\n\nPassages:\n{p}")


def generate_qa(chunks_by_doc, model, tok, num_questions=2, judge_llm=None, log=None):
    """CuratorKIT QA generation + grounding gate, local models only."""
    from curatorkit.schema import DataSample
    from curatorkit.generators.qa_generator import QAGenerationTask
    llm = LocalLLM(model, tok, "tiny-aya-global(local)")
    samples = [DataSample(source_uri=f"doc://{d}", input=c, task_type="instruction_following",
                          metadata={"doc": d, "chunk_index": i})
               for d, cs in chunks_by_doc.items() for i, c in enumerate(cs)]
    task = QAGenerationTask(llm=llm, num_questions=num_questions, concurrency=1, prompt_template=QA_PROMPT)
    qa = task.run(samples)
    if log:
        log(f"CuratorKIT QA generation: {len(samples)} chunks -> {len(qa)} QA pairs")
    report = {"chunks": len(samples), "generated": len(qa)}
    if judge_llm is not None:
        from curatorkit.gates.hallucination import HallucinationGate
        gate = HallucinationGate(llm=judge_llm, threshold=0.7)
        qa, rejected = gate.run(qa)
        report["grounding_gate_rejected"] = len(rejected)
    by_text = {c: (d, i) for d, cs in chunks_by_doc.items() for i, c in enumerate(cs)}
    report["raw_examples"] = [{"q": s.instruction, "a": s.output} for s in qa[:12]]
    out = []
    for s in qa:
        ctx = s.input
        if ctx not in by_text or not s.output:
            continue
        ans = s.output.strip().strip(".")
        if len(ans.split()) > 12 or not _contains(ctx, [ans]):
            continue  # keep short, extractive answers so they can be scored and edited
        d, i = by_text[ctx]
        out.append({"qid": hashlib.sha256((s.instruction + ans).encode()).hexdigest()[:12], "question": s.instruction.strip(),
                    "answers": [ans], "paragraph_id": pid(ctx), "doc": d})
    report["extractive_kept"] = len(out)
    return out, report


def build(docs_folder, out_dir, cfg, model, tok, verify_fn=None, judge_llm=None, n_per_cell=60, probe_set="docs",
          log=None, seed=7):
    from ..audit.generate import generate
    k = cfg["prompt"]["passages_default"]
    docs = {d: t for d, t in read_documents(docs_folder).items() if not d.startswith("__error__")}
    chunks_by_doc = {d: chunk(t) for d, t in docs.items()}
    chunks_by_doc = {d: c for d, c in chunks_by_doc.items() if c}
    names = sorted(chunks_by_doc)
    rng = random.Random(seed)
    rng.shuffle(names)
    half = max(1, len(names) // 2)
    split_of = {d: ("val" if i < half else "test") for i, d in enumerate(names)}
    sources, report = generate_qa(chunks_by_doc, model, tok, judge_llm=judge_llm, log=log)
    manifest = {"probe_set": probe_set, "documents": len(docs), "split_of_document": split_of, "qa": report,
                "cells": {}, "failures": {}}
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for split in ("val", "test"):
        paras = [Paragraph(pid(c), d, c) for d in names if split_of[d] == split for c in chunks_by_doc[d]]
        if not paras:
            continue
        corpus = Corpus(paras)
        srcs = [s for s in sources if split_of[s["doc"]] == split]
        wp = wrong_answer_pool(srcs)
        outside = ["Zorvathia Ltd", "Quellmark", "Brennoch Plan", "Ondrelle", "Karvessa Gold", "Vantrel Policy"]
        items = []
        for cat, ctx in (("A", "C1"), ("U1", "C2"), ("U1", "C3"), ("U2", "C1"), ("U5", "C4")):
            got, fails = build_category(corpus, rng, probe_set, split, cat, ctx, srcs, int(n_per_cell * 1.6), k,
                                        wrong_pool=wp, outside_entities=outside)
            if verify_fn and got:
                keep = verify_fn(got)
                got = [it for it, ok in zip(got, keep) if ok]
            items += got[:n_per_cell]
            manifest["cells"][f"{split}/{cat}/{ctx}"] = len(got[:n_per_cell])
            if fails:
                manifest["failures"][f"{split}/{cat}/{ctx}"] = fails
        # U3 / U4 generated by the local model, kept only if the judge calls them insufficient
        gen_items = []
        for cat, prompt in (("U3", U3_PROMPT), ("U4", U4_PROMPT)):
            picks = [rng.choice(srcs) for _ in range(int(n_per_cell * 1.6))] if srcs else []
            ctxs = []
            for s in picks:
                g = corpus.by_id[s["paragraph_id"]]
                ps, _ = corpus._place(rng, corpus.distractors(rng, g, k - 1, ()), g.text)
                ctxs.append((s, ps))
            qs = generate(model, tok, [prompt.format(p=("\n\n".join(ps) if cat == "U4" else corpus.by_id[s["paragraph_id"]].text))
                                       for s, ps in ctxs], max_new_tokens=48) if ctxs else []
            cands = []
            for (s, ps), q in zip(ctxs, qs):
                qq = q[0].strip().split("\n")[0].strip().strip('"')
                if not qq.endswith("?") or len(qq.split()) < 4:
                    continue
                src = dict(s, qid=s["qid"] + cat, question=qq, answers=[], twin_source=s)
                cands.append(make_item(probe_set, split, cat, "C1", src, {"passages": ps, "gold_passage_index": None}))
            if verify_fn and cands:
                keep = verify_fn(cands)
                cands = [it for it, ok in zip(cands, keep) if ok]
            gen_items += cands[:n_per_cell]
            manifest["cells"][f"{split}/{cat}/C1 (generated)"] = len(cands[:n_per_cell])
        items += gen_items
        for it in items:
            if it["label"] == "abstain":
                tw = twin_of(it, corpus, rng, k)
                it["twin"] = {key: tw[key] for key in ("question", "passages", "gold_passage_index", "gold_answers")} if tw else None
        with open(out / f"paragraphs_{split}.jsonl", "w", encoding="utf-8") as f:
            for p in corpus.paragraphs:
                f.write(json.dumps({"id": p.id, "doc": p.doc, "text": p.text}, ensure_ascii=False) + "\n")
        with open(out / f"items_{split}.jsonl", "w", encoding="utf-8") as f:
            for it in items:
                f.write(json.dumps(it, ensure_ascii=False) + "\n")
    if (out / "items_test.jsonl").exists():
        manifest["test_lock_sha256"] = hashlib.sha256((out / "items_test.jsonl").read_bytes()).hexdigest()
        (out / "TEST_LOCK.txt").write_text(manifest["test_lock_sha256"] + "\n")
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False), encoding="utf-8")
    return manifest
